// 同名词条（如“流年”紫微／八字口径不同）：悬停时按所在命盘系统取
export function glossaryFor(term: string, group?: GlossaryGroup): GlossaryEntry | undefined {
  const all = GLOSSARY.filter((g) => g.term === term);
  return all.find((g) => g.group === group) ?? all[0];
}
